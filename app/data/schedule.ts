export function getSessionDateTime(session: ScheduleSession) {
  return new Date(`${session.date}T${session.startTime}:00+01:00`)
}

export function getCurrentOrNextSession() {
  const now = new Date()

  const sortedSessions = [...scheduleSessions].sort((a, b) => {
    return getSessionDateTime(a).getTime() - getSessionDateTime(b).getTime()
  })

  const nextSession = sortedSessions.find((session) => {
    return getSessionDateTime(session).getTime() >= now.getTime()
  })

  return nextSession || sortedSessions[sortedSessions.length - 1]
}

export function getCountdownToSession(session: ScheduleSession) {
  const now = new Date()
  const sessionTime = getSessionDateTime(session)

  const difference = sessionTime.getTime() - now.getTime()

  if (difference <= 0) {
    return {
      days: 0,
      hours: 0,
      minutes: 0,
      seconds: 0,
      label: "Now",
    }
  }

  const days = Math.floor(difference / (1000 * 60 * 60 * 24))
  const hours = Math.floor(
    (difference % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60)
  )
  const minutes = Math.floor(
    (difference % (1000 * 60 * 60)) / (1000 * 60)
  )
  const seconds = Math.floor((difference % (1000 * 60)) / 1000)

  return {
    days,
    hours,
    minutes,
    seconds,
    label: `${days}d ${hours}h ${minutes}m`,
  }
}